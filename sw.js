/**
 * B&B Shuffle - service worker (PWA app shell)
 *
 * Scope: the repo root (this file's own directory), so it controls the portal
 * and every Engine-V2 page. It exists to make the app installable and to serve
 * the shell when offline - NOT to freeze the app in time, so the freshness
 * rules matter:
 *
 *   - Navigations and HTML/JS/CSS: NETWORK-FIRST. A redeploy is picked up on
 *     the next load; the cache is only a fallback when the network fails.
 *   - Static art/icons/fonts: CACHE-FIRST, refreshed in the background.
 *   - The complete published site is precached from sw-manifest.json on
 *     install, so an installed device keeps working with no network at all.
 *   - /api/*          : never touched (the backend must always be live).
 *   - cache:'no-store' requests stay network-first, but fall back to the cached
 *     copy when offline (the card catalogue fetches its deck JSON that way).
 *
 * Bump VERSION to invalidate every cache on the next visit.
 */
'use strict';

const VERSION = 'bb-shuffle-v2.11';
// Every cache this worker owns starts with PREFIX; anything else in Cache Storage
// (notably the in-browser model runtime's own buckets) is left strictly alone.
const PREFIX = 'bb-shuffle-';
const SHELL_CACHE = VERSION + '-shell';
const RUNTIME_CACHE = VERSION + '-runtime';

// Generated by scripts/build_sw_manifest.py. When it is missing (local preview),
// the short SHELL list below keeps the app installable.
const MANIFEST = 'sw-manifest.json';
const PRECACHE_BATCH = 24;

// The offline shell. Kept to files that exist in BOTH the main repo and the
// static fork; everything else is cached on first use at runtime. Added
// individually so a single 404 cannot abort the install.
const SHELL = [
  './',
  'index.html',
  'Engine-V2/player.html',
  'Engine-V2/css/player.css',
  'shared/css/base.css',
  'shared/js/fab.js',
  'shared/js/pwa.js',
  'Engine-V2/js/utils.js',
  'Engine-V2/js/config.js',
  'Engine-V2/js/card-face.js',
  'Engine-V2/js/game-state.js',
  'Engine-V2/js/player.js',
  'Engine-V2/js/header-menu.js',
  'Engine-V2/js/landscape-controls.js',
  'Engine-V2/js/cardback-theme.js',
  'Engine-V2/js/webllm-provider.js',
  'manifest.webmanifest',
  'shared/img/favicon.ico',
  'shared/img/favicon.png',
  'shared/img/pwa-192.png',
  'shared/img/pwa-512.png',
  'shared/img/pwa-maskable-512.png',
  'shared/img/apple-touch-icon.png'
];

// Static asset types that are safe to serve from cache first.
const ASSET_RE = /\.(?:png|jpe?g|gif|svg|webp|avif|ico|woff2?|ttf)$/i;

async function precache() {
  const cache = await caches.open(SHELL_CACHE);
  let files = SHELL;

  try {
    const response = await fetch(MANIFEST, { cache: 'reload' });
    if (response.ok) {
      const data = await response.json();
      const list = Array.isArray(data) ? data : (Array.isArray(data.files) ? data.files : null);
      if (list && list.length) files = list;
    }
  } catch (_) { /* keep the shell fallback */ }

  for (let i = 0; i < files.length; i += PRECACHE_BATCH) {
    const batch = files.slice(i, i + PRECACHE_BATCH);
    await Promise.all(batch.map(async function (url) {
      try {
        if (await cache.match(url)) return;
        await cache.add(new Request(url, { cache: 'reload' }));
      } catch (_) {
        /* a missing or pruned file must not abort the install */
      }
    }));
  }
}

self.addEventListener('install', function (event) {
  event.waitUntil((async function () {
    await precache();
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', function (event) {
  event.waitUntil((async function () {
    const keys = await caches.keys();
    // Only ever reap OUR OWN stale version caches. The old filter deleted every
    // cache that did not start with VERSION, which silently wiped the in-browser
    // model's downloaded weights (the WebLLM runtime keeps them in `webllm/model`
    // and friends) on every app update - forcing a multi-gigabyte re-download.
    await Promise.all(keys
      .filter(function (key) { return key.indexOf(PREFIX) === 0 && key.indexOf(VERSION) !== 0; })
      .map(function (key) { return caches.delete(key); }));
    await self.clients.claim();
  })());
});

// Retry / finish the full-site download when the page asks for it. The install
// event already runs this; the message covers a failed install or cache eviction.
self.addEventListener('message', function (event) {
  if (!event.data || event.data.type !== 'PRECACHE_ALL') return;
  event.waitUntil(precache().then(function () {
    if (event.source) event.source.postMessage({ type: 'PRECACHE_DONE' });
  }));
});

function bypass(url, request) {
  if (url.origin !== self.location.origin) return true;
  if (url.pathname.indexOf('/api/') !== -1) return true;
  return false;
}

async function putIn(cacheName, request, response) {
  if (!response || !response.ok) return;
  try {
    const cache = await caches.open(cacheName);
    await cache.put(request, response.clone());
  } catch (_) { /* opaque / already-consumed - ignore */ }
}

self.addEventListener('fetch', function (event) {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (bypass(url, request)) return;   // fall through to the network

  // Navigations: network-first, cached document as the offline fallback.
  if (request.mode === 'navigate') {
    event.respondWith((async function () {
      try {
        const fresh = await fetch(request);
        await putIn(RUNTIME_CACHE, request, fresh);
        return fresh;
      } catch (_) {
        return (await caches.match(request, { ignoreSearch: true }))
          || (await caches.match('index.html', { ignoreSearch: true }))
          || (await caches.match('Engine-V2/player.html'))
          || Response.error();
      }
    })());
    return;
  }

  // Static art/icons/fonts: cache-first, refresh in the background.
  if (ASSET_RE.test(url.pathname)) {
    event.respondWith((async function () {
      // ignoreSearch: the build stamps ?v=<content hash> onto CSS/JS URLs, and
      // the precache list holds plain paths, so match on the path alone.
      const cached = await caches.match(request, { ignoreSearch: true });
      if (cached) {
        fetch(request).then(function (res) {
          return putIn(RUNTIME_CACHE, request, res);
        }).catch(function () {});
        return cached;
      }
      const fresh = await fetch(request);
      await putIn(RUNTIME_CACHE, request, fresh);
      return fresh;
    })());
    return;
  }

  // HTML (non-navigation), JS, CSS, JSON: network-first, cache as fallback.
  event.respondWith((async function () {
    try {
      const fresh = await fetch(request);
      await putIn(RUNTIME_CACHE, request, fresh);
      return fresh;
    } catch (err) {
      // Same reason as above: a ?v=<hash> URL and its precached plain path are
      // the same file, so an offline request must still find it.
      const cached = await caches.match(request, { ignoreSearch: true });
      if (cached) return cached;
      throw err;
    }
  })());
});
